#!/usr/bin/env bash
# Generates a fresh 4-validator QBFT network (keys + genesis) and the docker-compose file.
# Idempotent: refuses to overwrite an existing network unless --force is given.
# Usage: ./setup.sh [--force]
set -euo pipefail
cd "$(dirname "$0")"

BESU_IMAGE="hyperledger/besu:26.9.0"
NET_DIR="network"
SUBNET_PREFIX="172.31.27"  # 172.28/172.29 are taken by another project's Docker networks

if [[ -d "$NET_DIR" && "${1:-}" != "--force" ]]; then
  echo "network/ already exists; use --force to regenerate (this wipes chain state)." >&2
  exit 1
fi
rm -rf "$NET_DIR" generated  # besu creates generated/ itself and refuses an existing one

# Docker on Windows needs a native path for the bind mount.
HOST_DIR="$(pwd -W 2>/dev/null || pwd)"
# Generate inside the container, then copy out: Docker Desktop's file sharing can report a
# fresh bind-mounted directory as pre-existing, which besu rejects.
MSYS_NO_PATHCONV=1 docker run --rm -v "$HOST_DIR:/cfg" --entrypoint /bin/bash "$BESU_IMAGE" -c \
  "/opt/besu/bin/besu operator generate-blockchain-config --config-file=/cfg/qbftConfig.json --to=/tmp/gen \
   && cp -r /tmp/gen /cfg/generated"

mkdir -p "$NET_DIR"
cp generated/genesis.json "$NET_DIR/genesis.json"
i=1
for keydir in generated/keys/*/; do
  mkdir -p "$NET_DIR/node$i/data"
  cp "$keydir/key.priv" "$NET_DIR/node$i/key"
  cp "$keydir/key.pub" "$NET_DIR/node$i/key.pub"
  i=$((i + 1))
done
rm -rf generated

BOOT_PUB="$(sed 's/^0x//' "$NET_DIR/node1/key.pub")"
BOOTNODE="enode://${BOOT_PUB}@${SUBNET_PREFIX}.11:30303"

{
  echo "# Generated by setup.sh. Do not edit by hand."
  echo "name: provecps-besu"
  echo "networks:"
  echo "  qbft:"
  echo "    ipam:"
  echo "      config:"
  echo "        - subnet: ${SUBNET_PREFIX}.0/24"
  echo "services:"
  for n in 1 2 3 4; do
    echo "  node$n:"
    echo "    image: $BESU_IMAGE"
    echo "    container_name: besu-node$n"
    echo "    cap_add: [NET_ADMIN]   # lets experiments inject delay/partitions with tc inside the container"
    echo "    networks:"
    echo "      qbft:"
    echo "        ipv4_address: ${SUBNET_PREFIX}.1$n"
    echo "    ports:"
    echo "      - \"$((8544 + n)):8545\""
    echo "    volumes:"
    echo "      - ./network/genesis.json:/config/genesis.json:ro"
    echo "      - ./network/node$n/key:/config/key:ro"
    echo "      - ./network/node$n/data:/data"
    echo "    command:"
    echo "      - --genesis-file=/config/genesis.json"
    echo "      - --node-private-key-file=/config/key"
    echo "      - --data-path=/data"
    echo "      - --p2p-host=${SUBNET_PREFIX}.1$n"
    echo "      - --rpc-http-enabled"
    echo "      - --rpc-http-host=0.0.0.0"
    echo "      - --rpc-http-api=ETH,NET,WEB3,QBFT,TXPOOL,ADMIN"
    echo "      - --host-allowlist=*"
    echo "      - --rpc-http-cors-origins=all"
    echo "      - --min-gas-price=0"
    echo "      - --sync-min-peers=1"
    if [[ $n -ne 1 ]]; then
      echo "      - --bootnodes=$BOOTNODE"
    fi
  done
} > docker-compose.yml

echo "Generated 4-validator QBFT network. Start with: docker compose up -d"
